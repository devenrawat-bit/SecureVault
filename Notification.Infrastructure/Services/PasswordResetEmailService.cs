using Notification.Application.Interfaces;
using System.Net;

namespace Notification.Infrastructure.Services
{
    public sealed class PasswordResetEmailService : IPasswordResetEmailService //no inheritance of this class will be now allowed by the sealed keyword 
    {
        private readonly IEmailSender _emailSender;

        public PasswordResetEmailService(IEmailSender emailSender)
        {
            _emailSender = emailSender;
        }

        /// <summary>
        /// This method is used to send Password reset email to the user that is carried from the Auth service 
        /// </summary>
        /// <param name="userId"></param>
        /// <param name="recipientEmail">Email of the user for which the reset password is intended for.</param>
        /// <param name="resetLink">The link on which the user will click to land on the reset password page </param>
        /// <param name="cancellationToken"></param>
        /// <returns></returns>
        /// <exception cref="ArgumentException"></exception>
        public async Task SendPasswordResetEmailAsync(
            Guid userId,
            string recipientEmail,
            string resetLink, // The reset link will be generated by the Auth MS. 
            CancellationToken cancellationToken = default)
        {
            // Validate the recipient email.
            if (string.IsNullOrWhiteSpace(recipientEmail))
            {
                throw new ArgumentException(
                    "Recipient email is required.",
                    nameof(recipientEmail));
            }

            // Validate the password-reset link. As it don't have the malicious link like "javascript:alert('XSS')".
            if (!Uri.TryCreate(resetLink, UriKind.Absolute, out var resetUri) ||
                (resetUri.Scheme != Uri.UriSchemeHttps &&
                 !(resetUri.IsLoopback && resetUri.Scheme == Uri.UriSchemeHttp)))
            {
                throw new ArgumentException(
                    "The password-reset link is invalid.",
                    nameof(resetLink));
            }

            // Encode the reset link before inserting it into HTML. So that it doesn't get misinterpreted while traveling to the URL.
            var safeResetLink = WebUtility.HtmlEncode(resetLink);

            // Define the email subject.
            var subject = "Reset your SecureVault password";

            // Create the HTML email body.
            var htmlBody = $"""
                <!DOCTYPE html>
                <html>
                <body>
                    <h2>Password Reset Request</h2>

                    <p>
                        We received a request to reset your SecureVault password.
                    </p>

                    <p>
                        <a href="{safeResetLink}">
                            Reset your password
                        </a>
                    </p>

                    <p>
                        If you did not request this password reset,
                        you can ignore this email.
                    </p>

                    <p>
                        For your security, do not share this link with anyone.
                    </p>

                    <p>SecureVault Team</p>
                </body>
                </html>
                """;

            // Send the email using the existing SMTP email sender.
            await _emailSender.SendAsync(
                recipientEmail,
                subject,
                htmlBody,
                cancellationToken);
        }
    }
}
